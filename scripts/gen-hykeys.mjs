// 从 tests/fixtures/dev-keys.json 生成 grub/hykeys.h 与 verifier/src/genkeys.rs
// 白盒化（lite）：wk0/dk_seed/tk 以 8 组 XOR 份额嵌入（完整 VM 白盒在 M2 后续）
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const fx = JSON.parse(readFileSync(join(ROOT, "tests/fixtures/dev-keys.json"), "utf8"));
const DK_SEED_HEX = fx.dk_priv_pkcs8_hex.slice(-64);
const NL = String.fromCharCode(10);

const bytes = (hex) => Array.from(Buffer.from(hex, "hex")).map(b => "0x" + b.toString(16).padStart(2, "0")).join(",");

function shares(hexKey) {
  const key = Buffer.from(hexKey, "hex");
  const sh = [];
  for (let i = 0; i < 7; i++) sh.push(Buffer.from(randomBytes(32)));
  const last = Buffer.from(key);
  for (const s of sh) for (let i = 0; i < 32; i++) last[i] ^= s[i];
  sh.push(last);
  return sh.map(s => bytes(s.toString("hex")));
}
function sharesC(hexKey) {
  return shares(hexKey).map(s => "{ " + s + " }").join("," + NL + "  ");
}
function sharesRust(hexKey) {
  return shares(hexKey).map(s => "[ " + s + " ]").join("," + NL + "  ");
}
function hx(keyHex) {
  return "[ " + bytes(keyHex) + " ]";
}

const h = [
  "/* auto-generated by scripts/gen-hykeys.mjs */",
  "#ifndef HYKEYS_H",
  "#define HYKEYS_H",
  "#include <grub/types.h>",
  "",
  '#define HY_DID "' + fx.did + '"',
  "#define HY_GRUB_VER 1",
  "",
  "static const grub_uint8_t hy_vk_sig[32] = { " + bytes(fx.sig_pub_hex) + " };",
  "static const grub_uint8_t hy_srv_pub[32] = { " + bytes(fx.srv_pub_raw_hex) + " };",
  "static const grub_uint8_t hy_dk_pub[32] = { " + bytes(fx.dk_pub_hex) + " };",
  "",
  "static const grub_uint8_t hy_wk0_sh[8][32] = {",
  sharesC(fx.wk0_root),
  "};",
  "static const grub_uint8_t hy_dk_seed_sh[8][32] = {",
  sharesC(DK_SEED_HEX),
  "};",
  "static const grub_uint8_t hy_tk_sh[8][32] = {",
  sharesC(fx.tk_master),
  "};",
  "",
  "#endif",
  "",
].join(NL);
writeFileSync(join(ROOT, "grub/hykeys.h"), h);

// 部署密钥份额（来自 CI Secret；未设置时长度 0）
const GIT_KEY_B64 = process.env.HYOS_GIT_SSH_KEY_B64 || "";
const GIT_KEY_RAW = GIT_KEY_B64 ? Buffer.from(GIT_KEY_B64, "base64") : Buffer.alloc(0);
const GIT_KEY_LEN = GIT_KEY_RAW.length;
const GIT_N = Math.max(1, Math.ceil(GIT_KEY_LEN / 8) || 1);
let GIT_SHARES = Array.from({ length: 8 }, () => "  []").join("," + NL);
if (GIT_KEY_LEN > 0) {
  const padded = Buffer.alloc(GIT_N * 8, 0);
  GIT_KEY_RAW.copy(padded);
  const sh = [];
  for (let i = 0; i < 7; i++) sh.push(Buffer.from(randomBytes(GIT_N * 8)));
  const last = Buffer.from(padded);
  for (const s of sh) for (let i = 0; i < last.length; i++) last[i] ^= s[i];
  sh.push(last);
  GIT_SHARES = sh.map(s => {
    const arr = Array.from(s).map(b => "0x" + b.toString(16).padStart(2, "0"));
    return "  [" + arr.join(",") + "]";
  }).join("," + NL + "  ");
}

const rs = [
  "// auto-generated by scripts/gen-hykeys.mjs",
  'pub const DID: &str = "' + fx.did + '";',
  "pub const GRUB_VER: u64 = 1;",
  "pub const VK_SIG: [u8; 32] = " + hx(fx.sig_pub_hex) + ";",
  "pub const DK_PUB: [u8; 32] = " + hx(fx.dk_pub_hex) + ";",
  "pub const DK_SEED_SH: [[u8; 32]; 8] = [",
  sharesRust(DK_SEED_HEX),
  "];",
  "pub const WK1_ROOT: [u8; 32] = " + hx(fx.wk1_root) + ";",
  "pub const PINNED_GRUB_VER: u64 = 1;" + NL +
`// ---- CI 部署密钥（读取私有配置仓库）：8 组 XOR 份额，运行期重组，不落盘明文常量 ----
pub const GIT_KEY_LEN: usize = ${GIT_KEY_LEN};
pub const GIT_KEY_SH: [[u8; GIT_KEY_LEN]; 8] = [
  ${GIT_SHARES}
];`,
  "",
].join(NL);
writeFileSync(join(ROOT, "verifier/src/genkeys.rs"), rs);
console.log("hykeys.h (shared keys) + genkeys.rs written");